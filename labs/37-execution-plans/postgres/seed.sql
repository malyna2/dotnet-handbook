INSERT INTO shipments (order_id, carrier, shipped_at, tracking_code)
SELECT o,
       (ARRAY['DHL','UPS','DPD','GLS','Nova Poshta'])[1 + floor(pg_temp.r(o * 8 + s, 71) * 5)::int],
       pg_temp.created_of(o, :n_orders) + (1 + pg_temp.r(o * 8 + s, 72) * 4) * interval '1 day',
       md5((o * 8 + s)::text)
FROM generate_series(1, :n_orders) AS o,
     generate_series(1, CASE WHEN pg_temp.r(o, 1) >= 0.05 AND pg_temp.r(o, 1) < 0.10
