-- Lab 37 — schema and deterministic seed for PostgreSQL.
--
-- Run it through ../seed.sh, which passes the scale:
--   small   100 000 customers,   500 000 orders  (~1.8 M order lines)  — tests and quick tries
--   medium  1 000 000 customers, 5 000 000 orders (~18 M order lines)  — the numbers in Chapter 37
--   large   2 000 000 customers, 20 000 000 orders (~72 M order lines) — if you have the disk
--
-- Every "random" value is a hash of the row's key, so every reader gets exactly the same
-- rows, the same statistics and — on the same PostgreSQL version — the same plans.
-- The data is skewed on purpose, the way real data is:
--   * customer 1 is a marketplace account that places 5% of all orders;
--   * customers 2–11 are B2B key accounts: 5% of orders between them, 10–40 lines each;
--   * product 1 is a bestseller in 8% of all order lines, products 2–101 share another 10%;
--   * country and city are correlated (Berlin only exists in DE);
--   * emails are stored in mixed case ("Anna.Kowalski42@Example.com").
-- The lab clock is fixed at 2026-09-01 00:00 UTC (table lab_clock); orders cover the three
-- years before it, so date-range queries behave the same whenever you run them.

\set ON_ERROR_STOP on
\timing on

\if :{?scale}
\else
  \set scale medium
\endif

SELECT CASE :'scale' WHEN 'small' THEN 100000 WHEN 'medium' THEN 1000000 WHEN 'large' THEN 2000000 END AS n_customers,
       CASE :'scale' WHEN 'small' THEN 500000 WHEN 'medium' THEN 5000000 WHEN 'large' THEN 20000000 END AS n_orders,
       50000 AS n_products
\gset

\if :{?n_customers}
\else
  \echo 'unknown scale: use small, medium or large'
  \quit
\endif

\echo Seeding scale :scale — :n_customers customers, :n_orders orders, :n_products products

-- ---------------------------------------------------------------------------
-- Schema (dropped and recreated: seeding is repeatable)
-- ---------------------------------------------------------------------------
DROP TABLE IF EXISTS shipments, order_lines, orders, products, customers, lab_clock CASCADE;
CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

CREATE TABLE lab_clock (now timestamptz NOT NULL);
INSERT INTO lab_clock VALUES ('2026-09-01 00:00:00+00');

CREATE TABLE customers (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       text        NOT NULL,
    name        text        NOT NULL,
    country     text        NOT NULL,          -- ISO 3166-1 alpha-2
    city        text        NOT NULL,
    tier        text        NOT NULL,          -- consumer | key_account | marketplace
    created_at  timestamptz NOT NULL
);

CREATE TABLE products (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku       text          NOT NULL,
    name      text          NOT NULL,
    category  text          NOT NULL,
    price     numeric(10,2) NOT NULL
);

CREATE TABLE orders (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    bigint        NOT NULL,
    status         text          NOT NULL,     -- open | paid | shipped | cancelled
    created_at     timestamptz   NOT NULL,
    total          numeric(12,2) NOT NULL,
    currency       char(3)       NOT NULL,
    shipping_note  text
);

CREATE TABLE order_lines (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    bigint        NOT NULL,
    product_id  bigint        NOT NULL,
    quantity    integer       NOT NULL,
    unit_price  numeric(10,2) NOT NULL
);

CREATE TABLE shipments (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       bigint      NOT NULL,
    carrier        text        NOT NULL,
    shipped_at     timestamptz NOT NULL,
    tracking_code  text        NOT NULL
);

-- ---------------------------------------------------------------------------
-- Deterministic generators (inlined by the planner, so they cost almost nothing)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION pg_temp.r(k bigint, salt int) RETURNS float8
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$ SELECT (hashint8extended(k, salt) & 2147483647)::float8 / 2147483648.0 $$;

-- Which customer placed order o: 5% the marketplace, 5% the key accounts, 90% everyone else.
CREATE OR REPLACE FUNCTION pg_temp.customer_of(o bigint, n_customers bigint) RETURNS bigint
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$ SELECT CASE WHEN pg_temp.r(o, 1) < 0.05 THEN 1
                  WHEN pg_temp.r(o, 1) < 0.10 THEN 2 + floor(pg_temp.r(o, 2) * 10)::bigint
                  ELSE 12 + floor(pg_temp.r(o, 3) * (n_customers - 11))::bigint END $$;

CREATE OR REPLACE FUNCTION pg_temp.lines_of(o bigint) RETURNS int
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$ SELECT CASE WHEN pg_temp.r(o, 1) < 0.05 THEN 1 + floor(pg_temp.r(o, 11) * 3)::int     -- marketplace: 1–3
                  WHEN pg_temp.r(o, 1) < 0.10 THEN 10 + floor(pg_temp.r(o, 11) * 31)::int   -- key account: 10–40
                  ELSE 1 + floor(pg_temp.r(o, 11) * 4)::int END $$;                         -- consumer: 1–4

-- Line k of order o. o * 64 + k is unique because an order has at most 40 lines.
CREATE OR REPLACE FUNCTION pg_temp.product_of(o bigint, k int, n_products bigint) RETURNS bigint
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$ SELECT CASE WHEN pg_temp.r(o * 64 + k, 12) < 0.08 THEN 1
                  WHEN pg_temp.r(o * 64 + k, 12) < 0.18 THEN 2 + floor(pg_temp.r(o * 64 + k, 13) * 100)::bigint
                  ELSE 102 + floor(pg_temp.r(o * 64 + k, 14) * (n_products - 101))::bigint END $$;

CREATE OR REPLACE FUNCTION pg_temp.qty_of(o bigint, k int) RETURNS int
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$ SELECT CASE WHEN pg_temp.r(o, 1) >= 0.05 AND pg_temp.r(o, 1) < 0.10
                  THEN 1 + floor(pg_temp.r(o * 64 + k, 15) * 50)::int
                  ELSE 1 + floor(pg_temp.r(o * 64 + k, 15) * 3)::int END $$;

CREATE OR REPLACE FUNCTION pg_temp.price_of(p bigint) RETURNS numeric
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$ SELECT round((5 + pg_temp.r(p, 21) * 495)::numeric, 2) $$;

-- Orders are spread evenly over the three years before the lab clock, in id order.
CREATE OR REPLACE FUNCTION pg_temp.created_of(o bigint, n_orders bigint) RETURNS timestamptz
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$ SELECT timestamptz '2023-09-01 00:00:00+00'
             + ((o - 1 + pg_temp.r(o, 41)) / n_orders) * interval '1096 days' $$;

-- Recent orders are mostly open or paid; old ones are mostly shipped.
CREATE OR REPLACE FUNCTION pg_temp.status_of(o bigint, n_orders bigint) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$ SELECT CASE WHEN pg_temp.created_of(o, n_orders) >= timestamptz '2026-08-02 00:00:00+00' THEN
                    CASE WHEN pg_temp.r(o, 51) < 0.40 THEN 'open' WHEN pg_temp.r(o, 51) < 0.70 THEN 'paid'
                         WHEN pg_temp.r(o, 51) < 0.95 THEN 'shipped' ELSE 'cancelled' END
                  ELSE
                    CASE WHEN pg_temp.r(o, 51) < 0.01 THEN 'open' WHEN pg_temp.r(o, 51) < 0.02 THEN 'paid'
                         WHEN pg_temp.r(o, 51) < 0.95 THEN 'shipped' ELSE 'cancelled' END
             END $$;

