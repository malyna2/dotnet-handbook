       pg_temp.price_of(pg_temp.product_of(o, k, :n_products))
FROM generate_series(1, :n_orders) AS o,
     generate_series(1, pg_temp.lines_of(o)) AS k;

\echo orders
INSERT INTO orders (id, customer_id, status, created_at, total, currency, shipping_note)
SELECT o,
       pg_temp.customer_of(o, :n_customers),
       pg_temp.status_of(o, :n_orders),
       pg_temp.created_of(o, :n_orders),
       (SELECT sum(pg_temp.qty_of(o, k) * pg_temp.price_of(pg_temp.product_of(o, k, :n_products)))
          FROM generate_series(1, pg_temp.lines_of(o)) AS k),
       'EUR',
       CASE WHEN pg_temp.r(o, 61) < 0.10 THEN 'Leave with the neighbour if nobody answers' END
FROM generate_series(1, :n_orders) AS o;

