\echo indexes and foreign keys
CREATE UNIQUE INDEX uq_customers_email ON customers (email);          -- case-sensitive
CREATE UNIQUE INDEX uq_products_sku ON products (sku);
-- Someone replaced the foreign-key index on orders.customer_id with this one, reasoning that
-- "it contains customer_id, so it covers it". It also serves ORDER BY created_at.
CREATE INDEX ix_orders_created_at_customer_id ON orders (created_at, customer_id);
CREATE INDEX ix_order_lines_order_id ON order_lines (order_id);
CREATE INDEX ix_order_lines_product_id ON order_lines (product_id);
CREATE INDEX ix_shipments_order_id ON shipments (order_id);
CREATE INDEX ix_customers_country_city ON customers (country, city);

ALTER TABLE orders      ADD CONSTRAINT fk_orders_customers      FOREIGN KEY (customer_id) REFERENCES customers (id);
ALTER TABLE order_lines ADD CONSTRAINT fk_order_lines_orders    FOREIGN KEY (order_id)    REFERENCES orders (id);
ALTER TABLE order_lines ADD CONSTRAINT fk_order_lines_products  FOREIGN KEY (product_id)  REFERENCES products (id);
ALTER TABLE shipments   ADD CONSTRAINT fk_shipments_orders      FOREIGN KEY (order_id)    REFERENCES orders (id);

